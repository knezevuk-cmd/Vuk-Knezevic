export const SCHOOL_WINGS: WingConfig[] = WING_BLUEPRINTS.map((bp, idx) => {
  const t = idx / (WING_BLUEPRINTS.length - 1);

  let chaseStages: WingConfig['chaseStages'];
  let targetMeters: number;

  if (idx === 49) {
    // Level 50 Finale: Goca -> Žir -> Direktorka (last 100m!)
    chaseStages = [
      { chaser: 'GOCA', meters: 700 },
      { chaser: 'ZIR', meters: 800 },
      { chaser: 'DIREKTORKA', meters: 100 },
    ];
    targetMeters = 1600;
  } else if (idx >= 25) {
    // Levels 26-49: Žir for the main stretch, then Direktorka ambushes for a shorter sprint!
    const mainMeters = Math.round(1320 + (idx - 25) * 45);
    const dirMeters = Math.round(280 + (idx - 25) * 5);
    chaseStages = [
      { chaser: 'ZIR', meters: mainMeters },
      { chaser: 'DIREKTORKA', meters: dirMeters },
    ];
    targetMeters = mainMeters + dirMeters;
  } else if (idx >= 9) {
    // Levels 10-25: Žir
    targetMeters = Math.round(720 + idx * 75);
    chaseStages = [{ chaser: 'ZIR', meters: targetMeters }];
  } else {
    // Levels 1-9: Goca
    targetMeters = Math.round(720 + idx * 75);
    chaseStages = [{ chaser: 'GOCA', meters: targetMeters }];
  }

  return {
    id: idx,
    name: { en: bp.enName, sr: bp.srName },
    subtitle: { en: bp.enSub, sr: bp.srSub },
    targetMeters,
    baseSpeed: Number((26 + t * 18).toFixed(1)),
    maxSpeed: Number((35 + t * 18).toFixed(1)),
    spawnInterval: Number(Math.max(0.54, 1.15 - t * 0.61).toFixed(2)),
    broomCooldown: Number(Math.max(1.75, 4.2 - t * 2.45).toFixed(2)),
    wallColor: bp.wallColor,
    wainscotColor: bp.wainscotColor,
    archColor: bp.archColor,
    floorLight: bp.floorLight,
    floorDark: bp.floorDark,
    lockerColor: bp.lockerColor,
    accentColor: bp.accentColor,
    allowedObstacles: bp.allowedObstacles,
    chomperWeaveChance: Number(Math.min(0.65, idx * 0.014).toFixed(2)),
    janitor: chaseStages[0].chaser,
    chaseStages,
  };
});

